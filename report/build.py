"""Build report/report.html and report/report.pdf from report/report.md.

  uv run python report/build.py

Inserts results/tables.md (generated by analyze.py) at <!-- TABLES -->, converts Markdown
to HTML, and prints to PDF with a headless Edge/Chrome (pandoc is not required).
"""

import re
import shutil
import subprocess
import sys
from pathlib import Path

import markdown

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

BROWSERS = [
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    "msedge", "chrome", "chromium", "google-chrome",
]

CSS = """
@page { size: A4; margin: 18mm 17mm; }
body { font-family: Georgia, 'Times New Roman', serif; font-size: 10.5pt; line-height: 1.42; color: #111; }
h1.title { font-size: 17pt; text-align: center; margin: 0 0 6px; line-height: 1.25; }
p.meta { text-align: center; color: #444; margin: 2px 0; font-size: 10pt; }
h1 { font-size: 13pt; margin: 18px 0 6px; border-bottom: 1px solid #ccc; padding-bottom: 2px; }
h2 { font-size: 11.5pt; margin: 14px 0 4px; }
h3 { font-size: 10.5pt; margin: 12px 0 4px; }
p, li { text-align: justify; }
code { font-family: Consolas, monospace; font-size: 9pt; }
pre { background: #f6f6f4; padding: 6px 8px; font-size: 8.5pt; white-space: pre-wrap; }
blockquote { margin: 6px 16px; color: #333; font-size: 9.5pt; border-left: 3px solid #ddd; padding-left: 8px; }
table { border-collapse: collapse; margin: 8px auto; font-size: 8.5pt; }
th, td { border: 1px solid #ccc; padding: 2px 6px; }
th { background: #f2f2ef; }
figure { margin: 10px auto; text-align: center; break-inside: avoid; }
figure img { max-width: 100%; }
figcaption { font-size: 9pt; color: #333; margin-top: 3px; text-align: center; }
.appendix-tables table { font-size: 7.5pt; }
"""


def main() -> None:
    src = (HERE / "report.md").read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", src, flags=re.S)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip().strip('"')
        src = src[m.end():]
    tables = (ROOT / "results" / "tables.md").read_text(encoding="utf-8")
    tables = tables.replace("### ", "#### ")
    src = src.replace("<!-- TABLES -->", '<div class="appendix-tables" markdown="1">\n\n' + tables + "\n</div>")

    n = 0

    def fig(mm):
        nonlocal n
        n += 1
        cap, path, width = mm.group(1), mm.group(2), mm.group(3) or "90%"
        return (f'<figure><img src="{path}" style="width:{width}"><figcaption><b>Figure {n}.</b> {cap}'
                f"</figcaption></figure>")

    src = re.sub(r"!\[(.*?)\]\((.*?)\)(?:\{width=([\d.]+%)\})?", fig, src)
    body = markdown.markdown(src, extensions=["tables", "fenced_code", "md_in_html"])
    head = (f'<h1 class="title">{meta.get("title", "")}</h1><p class="meta">{meta.get("author", "")}</p>'
            f'<p class="meta">{meta.get("date", "")}</p>')
    html = (f'<!doctype html><html><head><meta charset="utf-8"><title>{meta.get("title", "Report")}</title>'
            f"<style>{CSS}</style></head><body>{head}{body}</body></html>")
    out_html = HERE / "report.html"
    out_html.write_text(html, encoding="utf-8")
    print(f"wrote {out_html}")

    exe = next((b for b in BROWSERS if Path(b).exists() or shutil.which(b)), None)
    if exe is None:
        print("no Edge/Chrome found; open report.html and print to PDF manually", file=sys.stderr)
        return
    out_pdf = HERE / "report.pdf"
    subprocess.run([exe, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={out_pdf}", out_html.as_uri()], check=True, timeout=120)
    print(f"wrote {out_pdf}")


if __name__ == "__main__":
    main()
